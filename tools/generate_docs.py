#!/usr/bin/env python3
"""Generate layout documentation from the layout data files.

Writes:

* ``docs/LAYOUTS.md`` - supported layouts with provenance and key rows;
* ``src/typoshift/integrations/claude_code/skill/reference.md`` - compact key
  tables the Claude Code skill uses when the CLI is unavailable.

Usage::

    python tools/generate_docs.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from typoshift.layouts import builtin_registry  # noqa: E402

ROWS = [
    ("Number row", ["TLDE"] + [f"AE{i:02d}" for i in range(1, 13)]),
    ("Top row", [f"AD{i:02d}" for i in range(1, 13)]),
    ("Home row", [f"AC{i:02d}" for i in range(1, 12)] + ["BKSL"]),
    ("Bottom row", ["LSGT"] + [f"AB{i:02d}" for i in range(1, 12)]),
]
REFERENCE_LAYOUTS = ["he", "ru", "uk", "ar", "el"]


def cell(ch: str | None) -> str:
    if ch is None:
        return "·"
    if ch == "|":
        return "\\|"
    if ch == "`":
        return "`` ` ``"
    if ch.isspace():
        return "␠"
    return ch


def layouts_md() -> str:
    reg = builtin_registry()
    out = [
        "# Supported keyboard layouts",
        "",
        "<!-- Generated by tools/generate_docs.py from src/typoshift/layouts/data. Do not edit. -->",
        "",
        "Every mapping is extracted from the [xkeyboard-config](https://gitlab.freedesktop.org/xkeyboard-config/"
        "xkeyboard-config) database by `tools/generate_layouts.py` (vendored sources in `tools/xkb`). Only the "
        "base and Shift levels are modelled. Dead keys are reproduced: a dead key followed by a letter composes "
        "(Greek `;` then `e` gives `έ`), and a dead key followed by a space gives the spacing accent.",
        "",
        "| Id | Layout | Script | Languages | XKB source | Keys | Dead keys |",
        "| --- | --- | --- | --- | --- | ---: | --- |",
    ]
    for lay in reg:
        dead = ", ".join(sorted({lay.keys[c][lv] for c, lvs in lay.dead_keys.items() for lv in lvs})) or "-"
        out.append(f"| `{lay.id}` | {lay.name} | {lay.script} | {', '.join(lay.languages)} | "
                   f"`{lay.source.get('symbols', '')}` | {len(lay.keys)} | {dead} |")
    out += [
        "",
        "## Layouts versus languages",
        "",
        "A layout defines which character each physical key produces. A language decides which reconstruction "
        "is plausible. TypoShift keeps the two apart:",
        "",
        "- Conversion is purely physical. It recovers the keystrokes under the source layout and replays them "
        "under the target layout.",
        "- Each candidate is scored against the language models of the target layout's languages (configurable "
        "with `layout_languages`).",
        "- Layouts whose base and Shift levels are identical produce identical candidates. For example, Polish "
        "(Programmers) is identical to English (US) and needs AltGr for Polish letters. TypoShift reports the "
        "first such layout and lists the others as `equivalent_layouts`. The language model, not the layout, "
        "decides whether the text is English or Polish.",
        "",
        "## Platform differences",
        "",
        "The XKB definitions match the standard Windows layouts for letters. Punctuation can differ on other "
        "platforms. macOS \"Russian\" (not \"Russian - PC\"), macOS \"Arabic\" and Hebrew-QWERTY are different "
        "layouts and are not built in. You can add them as custom layouts (see `docs/CUSTOM_LAYOUTS.md`).",
        "",
        "## Key rows",
        "",
        "Keys are listed left to right. `·` means the layout has no character on that key at that level. "
        "`LSGT` is the extra ISO key next to left Shift, and `BKSL` is the backslash key.",
        "",
    ]
    for lay in reg:
        out.append(f"### {lay.name} (`{lay.id}`)")
        out.append("")
        out.append("| Row | Base | Shift |")
        out.append("| --- | --- | --- |")
        for name, codes in ROWS:
            base = " ".join(cell(lay.keys.get(c, (None, None))[0]) for c in codes)
            shift = " ".join(cell(lay.keys.get(c, (None, None))[1]) for c in codes)
            out.append(f"| {name} | {base} | {shift} |")
        if lay.notes:
            out.append("")
            out.append(f"Note: {lay.notes}")
        out.append("")
    return "\n".join(out)


def reference_md() -> str:
    reg = builtin_registry()
    en = reg.get("en-US")
    out = [
        "# TypoShift key reference",
        "",
        "<!-- Generated by tools/generate_docs.py. Do not edit. -->",
        "",
        "Use this only when the `typoshift` CLI is unavailable. Each table pairs the character a layout "
        "produces with the English (US) character on the same physical key, unshifted and with Shift. To "
        "reconstruct English typed on layout X, replace each X character with its English pair. To "
        "reconstruct X typed on English, go the other way.",
        "",
    ]
    for lid in REFERENCE_LAYOUTS:
        lay = reg.get(lid)
        out.append(f"## {lay.name} (`{lay.id}`) ↔ English (US)")
        out.append("")
        out.append("| Level | " + lay.id + " → en-US |")
        out.append("| --- | --- |")
        for level, label in ((0, "Base"), (1, "Shift")):
            pairs = []
            for _, codes in ROWS:
                for code in codes:
                    a = lay.keys.get(code, (None, None))[level]
                    b = en.keys.get(code, (None, None))[level]
                    if a and b and a != b:
                        pairs.append(f"{cell(a)}→{cell(b)}")
            out.append(f"| {label} | {' '.join(pairs)} |")
        if lay.sequences:
            seqs = ", ".join(f"{s}→{cell(en.keys[c][lv])}" for s, (c, lv) in lay.sequences.items())
            out.append("")
            out.append(f"Multi-character keys: {seqs}")
        if lay.dead_keys:
            out.append("")
            out.append("Dead keys: " + ", ".join(
                f"{cell(lay.keys[c][lv])} (on the en-US {cell(en.keys[c][lv])} key)"
                for c, lvs in lay.dead_keys.items() for lv in sorted(lvs)) + ". They combine with the next letter.")
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    targets = {
        ROOT / "docs" / "LAYOUTS.md": layouts_md(),
        ROOT / "src" / "typoshift" / "integrations" / "claude_code" / "skill" / "reference.md": reference_md(),
    }
    stale = []
    for path, text in targets.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated docs:", ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
